import os
import re
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Dict, Iterable, List, Optional, Sequence

import yaml

from slsec import DEFAULT_SOURCE_URL, __version__
from slsec.config import (
    CONFIG_FILENAMES,
    MODES,
    SAST_ENGINES,
    SCA_PROVIDERS,
    ConfigError,
    bundled_text,
    find_repo_root,
    load_config,
)

SLSEC_PLACEHOLDER = "SLSEC"
PROFILES = ("base", "terraform", "docker", "github-actions", "jenkins", "java", "node", "python", "go", "dotnet")
LANGUAGE_PROFILES = ("java", "node", "python", "go", "dotnet")
CHECKOV_PROFILES = frozenset({"terraform", "docker"})  # profiles that add the slsec-checkov hook
# pin for the Semgrep CE engine (installed into the slsec-sast hook env)
SEMGREP_DEPENDENCY = "semgrep>=1.120,<2"  # keep in sync with the `semgrep` extra in pyproject.toml (1.120 = first win_amd64 wheels)
PRE_COMMIT_CONFIG = ".pre-commit-config.yaml"

# Config files each profile drops into the repo root: (bundled path parts, destination)
PROFILE_FILES: Dict[str, List[tuple]] = {
    "base": [(("configs", "gitleaks", "gitleaks.toml"), ".gitleaks.toml")],
    "terraform": [(("configs", "tflint", ".tflint.hcl"), ".tflint.hcl")],
    "docker": [(("configs", "hadolint", ".hadolint.yaml"), ".hadolint.yaml")],
    "github-actions": [(("configs", "zizmor", "zizmor.yml"), "zizmor.yml")],
    "jenkins": [(("configs", "groovylint", ".groovylintrc.json"), ".groovylintrc.json")],
}

SKIP_DIRS = {".git", ".terraform", ".terragrunt-cache", "node_modules", ".venv", "venv", "vendor", "dist", "build",
             "target", "bin", "obj", ".gradle", "__pycache__", ".tox", ".mypy_cache"}

HEADER = """\
# Generated by slsec {version} (shift-left security). Re-run `slsec init --update`
# to pick up new pins. Docs: {source}
#
# Secrets (gitleaks) always block. IaC/lint behaviour is set by `mode` in .slsec.yaml.
# Skipping hooks with --no-verify only defers the problem: CI runs the same checks.
"""


# --------------------------------------------------------------------------- helpers


def _log(msg: str) -> None:
    print(msg, flush=True)


def detect_profiles(root: Path, max_files: int = 20000) -> List[str]:
    """Guess which profiles apply by looking at the files in the repo."""
    found = {"base"}
    seen = 0
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
        rel = Path(dirpath).relative_to(root).as_posix()
        for name in filenames:
            seen += 1
            lower = name.lower()
            if lower.endswith((".tf", ".tf.json", ".tofu")):
                found.add("terraform")
            elif lower in ("dockerfile", "containerfile") or lower.startswith(("dockerfile.", "containerfile.")) or lower.endswith(".dockerfile"):
                found.add("docker")
            elif lower.startswith("jenkinsfile") or (rel.split("/")[0] == "vars" and lower.endswith(".groovy")):
                found.add("jenkins")
            elif rel in (".github/workflows",) and lower.endswith((".yml", ".yaml")):
                found.add("github-actions")
            # language profiles are not exclusive with the above (a .py file can sit beside a Dockerfile)
            if lower in ("pom.xml", "build.gradle", "build.gradle.kts") or lower.endswith((".java", ".kt")):
                found.add("java")
            if lower == "package.json":
                found.add("node")
            if lower in ("pyproject.toml", "setup.py") or lower.endswith(".py") or (
                lower.startswith("requirements") and lower.endswith(".txt")
            ):
                found.add("python")
            if lower == "go.mod":
                found.add("go")
            if lower.endswith((".csproj", ".sln", ".cs", ".fsproj")):
                found.add("dotnet")
        if seen > max_files:
            break
    return [p for p in PROFILES if p in found]


def load_profile(name: str) -> dict:
    data = yaml.safe_load(bundled_text("templates", "profiles", f"{name}.yaml")) or {}
    return data


def _repo_key(repo: dict) -> str:
    return str(repo.get("repo"))


def _merge_repo(into: dict, new: dict) -> None:
    if "rev" in new:
        into["rev"] = new["rev"]
    existing_ids = {h.get("id") for h in into.get("hooks", [])}
    for hook in new.get("hooks", []):
        if hook.get("id") not in existing_ids:
            into.setdefault("hooks", []).append(hook)
        elif into.get("repo") == "local" and "additional_dependencies" in hook:
            # local hooks carry their tool pin in additional_dependencies; refresh only
            # that, so a team's own args/files/entry tweaks survive `init --update`
            for h in into["hooks"]:
                if h.get("id") == hook.get("id"):
                    h["additional_dependencies"] = list(hook["additional_dependencies"])


def load_sca_fragment(provider: str) -> dict:
    return yaml.safe_load(bundled_text("templates", "sca", f"{provider}.yaml")) or {}


def _remove_hooks(repos: List[dict], hook_ids: set) -> None:
    for repo in repos:
        if "hooks" in repo:
            repo["hooks"] = [h for h in repo["hooks"] if h.get("id") not in hook_ids]
    repos[:] = [r for r in repos if r.get("hooks") or "hooks" not in r]


def _apply_sast_engine(repos: List[dict], sast_engine: str) -> None:
    """semgrep needs the engine installed in the hook env; any other engine drops that pin."""
    for repo in repos:
        for hook in repo.get("hooks", []) or []:
            if hook.get("id") != "slsec-sast":
                continue
            deps = [d for d in hook.get("additional_dependencies", []) or [] if not str(d).startswith("semgrep")]
            if sast_engine == "semgrep":
                deps.append(SEMGREP_DEPENDENCY)
            if deps:
                hook["additional_dependencies"] = deps
            else:
                hook.pop("additional_dependencies", None)


def compose_config(
    profiles: Sequence[str],
    source_url: str,
    rev: str,
    existing: Optional[dict] = None,
    sca: str = "none",
    sast_engine: str = "opengrep",
) -> dict:
    """Merge profile fragments (and an existing config, if any) into one pre-commit config."""
    config: dict = dict(existing or {})
    config.setdefault("default_stages", ["pre-commit"])
    repos: List[dict] = [dict(r) for r in config.get("repos", [])]
    index = {_repo_key(r): r for r in repos}
    fragments = [load_profile(n) for n in ["base", *[p for p in profiles if p != "base"]]]
    if sca != "none":
        fragments.append(load_sca_fragment(sca))
    for fragment in fragments:
        for repo in fragment.get("repos", []):
            repo = {**repo, "hooks": [dict(h) for h in repo.get("hooks", [])]}
            if repo.get("repo") == SLSEC_PLACEHOLDER:
                repo = {"repo": source_url, "rev": rev, "hooks": repo["hooks"]}
            key = _repo_key(repo)
            if key in index:
                _merge_repo(index[key], repo)
            else:
                index[key] = repo
                repos.append(repo)
    # switching provider: drop the other providers' hooks (the only hooks slsec ever removes)
    _remove_hooks(repos, {f"slsec-{p}" for p in SCA_PROVIDERS if p not in ("none", sca)})
    _apply_sast_engine(repos, sast_engine)
    if sca != "none":
        types = list(config.get("default_install_hook_types") or [])
        for hook_type in ("pre-commit", "pre-push"):
            if hook_type not in types:
                types.append(hook_type)
        config["default_install_hook_types"] = types
    config["repos"] = repos
    # keep top-level keys in a readable order
    ordered = {k: config[k] for k in ("default_stages", "default_install_hook_types") if k in config}
    ordered.update({k: v for k, v in config.items() if k not in ordered and k != "repos"})
    ordered["repos"] = repos
    return ordered


def dump_config(config: dict, source_url: str) -> str:
    body = yaml.safe_dump(config, sort_keys=False, default_flow_style=False, width=120)
    return HEADER.format(version=__version__, source=source_url) + body


def _write(path: Path, text: str) -> None:
    # explicit LF so generated files don't flip line endings on Windows
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)


def _set_provider(text: str, key: str, value: str) -> str:
    """Rewrite `providers.<key>` in place, keeping the file's comments."""
    return re.sub(rf"^(\s+{key}:\s*)[A-Za-z]+", rf"\g<1>{value}", text, count=1, flags=re.M)


def _backup(path: Path) -> Path:
    bak = path.with_name(path.name + ".bak")
    shutil.copy2(path, bak)
    return bak


def _write_if_changed(path: Path, content: str, overwrite: bool) -> str:
    if path.exists():
        current = path.read_text(encoding="utf-8")
        if current == content:
            return "unchanged"
        if not overwrite:
            return "kept (differs from slsec default; use --force to replace)"
        bak = _backup(path)
        _write(path, content)
        return f"replaced (previous saved as {bak.name})"
    _write(path, content)
    return "created"


def _run(cmd: Sequence[str], cwd: Path) -> int:
    try:
        return subprocess.run(list(cmd), cwd=cwd).returncode
    except OSError as exc:
        _log(f"  ! could not run {cmd[0]}: {exc}")
        return 127


