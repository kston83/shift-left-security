def cmd_init(args: argparse.Namespace) -> int:
    root = find_repo_root(Path(args.path))
    if not (root / ".git").exists():
        _log(f"error: {root} is not a git repository (run `git init` first)")
        return 2
    source_url = args.source_url or os.environ.get("SLSEC_SOURCE_URL") or DEFAULT_SOURCE_URL
    rev = args.rev or f"v{__version__}"

    existing_settings = {}
    for name in CONFIG_FILENAMES:
        if (root / name).is_file():
            existing_settings = yaml.safe_load((root / name).read_text(encoding="utf-8")) or {}
            break

    providers_cfg = existing_settings.get("providers") or {}
    sca = args.sca
    if sca is None:
        sca = str(providers_cfg.get("sca", "none")) if args.update else "none"
    sast_engine = args.sast_engine
    if sast_engine is None:
        sast_engine = str(providers_cfg.get("sast_engine", "opengrep")) if args.update else "opengrep"
    if sca not in SCA_PROVIDERS or sast_engine not in SAST_ENGINES:
        _log(f"error: invalid providers in .slsec.yaml (sca={sca}, sast_engine={sast_engine})")
        return 2

    if args.profile:
        profiles = [p.strip() for p in args.profile.split(",") if p.strip()]
    elif args.update and existing_settings.get("profiles"):
        profiles = [str(p) for p in existing_settings["profiles"]]
    else:
        profiles = detect_profiles(root)
        _log(f"Detected profiles: {', '.join(profiles)}  (override with --profile)")
    unknown = [p for p in profiles if p not in PROFILES]
    if unknown:
        _log(f"error: unknown profile(s): {', '.join(unknown)}. Available: {', '.join(PROFILES)}")
        return 2
    if "base" not in profiles:
        profiles = ["base", *profiles]
    if CHECKOV_PROFILES.intersection(profiles) and sys.version_info >= (3, 15):
        _log(
            "  note: checkov (slsec-checkov) doesn't install on Python 3.15 yet: some of its dependencies\n"
            "        have no 3.15 wheels. Run pre-commit on Python 3.14, or add\n"
            "        `language_version: python3.14` to the slsec-checkov hook."
        )

    # 1. .pre-commit-config.yaml (merged with whatever the repo already has)
    pcc = root / PRE_COMMIT_CONFIG
    existing = None
    if pcc.exists():
        try:
            existing = yaml.safe_load(pcc.read_text(encoding="utf-8")) or {}
        except yaml.YAMLError as exc:
            _log(f"error: existing {PRE_COMMIT_CONFIG} is not valid YAML: {exc}")
            return 2
    merged = compose_config(profiles, source_url, rev, existing, sca=sca, sast_engine=sast_engine)
    content = dump_config(merged, source_url)
    if existing is not None and pcc.read_text(encoding="utf-8") != content:
        bak = _backup(pcc)
        _write(pcc, content)
        _log(f"  {PRE_COMMIT_CONFIG}: merged slsec hooks into existing config (previous saved as {bak.name})")
    else:
        _log(f"  {PRE_COMMIT_CONFIG}: {_write_if_changed(pcc, content, overwrite=True)}")

    # 2. tool config files
    for profile in profiles:
        for parts, dest in PROFILE_FILES.get(profile, []):
            status = _write_if_changed(root / dest, bundled_text(*parts), overwrite=args.force)
            _log(f"  {dest}: {status}")

    # 3. .slsec.yaml
    settings_path = next((root / n for n in CONFIG_FILENAMES if (root / n).exists()), root / ".slsec.yaml")
    if settings_path.exists():
        text = settings_path.read_text(encoding="utf-8")
        new_text = text
        for key, val, given in (("sca", sca, args.sca), ("sast_engine", sast_engine, args.sast_engine)):
            if given is not None:
                new_text = _set_provider(new_text, key, val)
        if new_text != text:
            _write(settings_path, new_text)
            _log(f"  {settings_path.name}: updated providers (sca={sca}, sast_engine={sast_engine})")
        else:
            _log(f"  {settings_path.name}: kept (edit it to change mode or exceptions)")
    else:
        text = bundled_text("templates", "slsec.yaml.tmpl").format(
            mode=args.mode, profiles=", ".join(profiles), sca=sca, sast_engine=sast_engine
        )
        _write(settings_path, text)
        _log(f"  {settings_path.name}: created (mode={args.mode})")

    # 4. git hooks
    if args.no_install:
        _log("\nSkipped hook installation (--no-install). Run: pre-commit install --install-hooks")
        return 0
    pre_commit = shutil.which("pre-commit")
    if not pre_commit:
        _log(
            "\npre-commit is not installed, so git hooks were not activated. Install it, then run\n"
            "  pre-commit install --hook-type pre-commit --hook-type pre-push\n"
            "Install options: `uv tool install pre-commit`, `pipx install pre-commit`, or `pip install --user pre-commit`."
        )
        return 0
    rc = _run([pre_commit, "install", "--hook-type", "pre-commit", "--hook-type", "pre-push"], root)
    if rc == 0:
        _log("\nDone. Hooks are active. First run downloads the scanners; try: pre-commit run --all-files")
    return rc


# --------------------------------------------------------------------------- doctor


class _Report:
    def __init__(self) -> None:
        self.failures = 0
        self.warnings = 0

    def ok(self, msg: str) -> None:
        _log(f"  [ok]   {msg}")

    def warn(self, msg: str) -> None:
        self.warnings += 1
        _log(f"  [warn] {msg}")

    def fail(self, msg: str) -> None:
        self.failures += 1
        _log(f"  [FAIL] {msg}")


def _version_tuple(rev: str) -> tuple:
    parts = []
    for p in str(rev).lstrip("v").split("."):
        digits = "".join(ch for ch in p if ch.isdigit())
        parts.append(int(digits) if digits else 0)
    return tuple(parts)


def find_slsec_repo(config: dict, source_url: Optional[str] = None) -> Optional[dict]:
    for repo in config.get("repos", []) or []:
        hook_ids = {h.get("id") for h in repo.get("hooks", []) or []}
        if any(str(i).startswith("slsec-") for i in hook_ids) or (source_url and repo.get("repo") == source_url):
            return repo
    return None


def _doctor_providers(r: "_Report", root: Path, config: dict, args: argparse.Namespace) -> None:
    try:
        cfg = load_config(root)
    except ConfigError:
        return
    sca = cfg.sca
    if sca == "snyk":
        if not shutil.which("snyk"):
            r.warn("sca=snyk but `snyk` is not on PATH (npm i -g snyk, or use the standalone binary)")
        else:
            authed = bool(os.environ.get("SNYK_TOKEN"))
            if not authed:
                try:
                    out = subprocess.run(["snyk", "config", "get", "api"], capture_output=True, text=True, timeout=15)
                    authed = out.returncode == 0 and bool(out.stdout.strip())
                except (OSError, subprocess.SubprocessError):
                    pass
            if authed:
                r.ok("snyk found and credentials look configured")
            else:
                r.warn("snyk is not authenticated: set SNYK_TOKEN or run `snyk auth`")
    elif sca == "jfrog":
        if not shutil.which("jf"):
            r.warn("sca=jfrog but the JFrog CLI (`jf`) is not on PATH")
        else:
            try:
                out = subprocess.run(["jf", "c", "show"], capture_output=True, text=True, timeout=15)
                configured = out.returncode == 0 and bool(out.stdout.strip())
            except (OSError, subprocess.SubprocessError):
                configured = False
            if configured:
                r.ok("jf found with a configured server")
            else:
                r.warn("no JFrog server configured: run `jf c add`")
    elif sca == "osv":
        if shutil.which("osv-scanner"):
            r.ok("osv-scanner found on PATH")
        else:
            r.ok("osv-scanner not on PATH: slsec downloads a pinned copy on first use")
    if sca != "none":
        hook_ids = {h.get("id") for repo in config.get("repos", []) or [] for h in repo.get("hooks", []) or []}
        if f"slsec-{sca}" not in hook_ids:
            r.warn(f"sca={sca} but hook slsec-{sca} is not in {PRE_COMMIT_CONFIG}: run `slsec init --update`")
        if not args.ci:
            if _git_hook_installed(root, "pre-push"):
                r.ok("git pre-push hook installed (dependency scan)")
            else:
                r.warn("git pre-push hook missing: run `pre-commit install --hook-type pre-push`")
    if set(detect_profiles(root)) & set(LANGUAGE_PROFILES):
        _log(
            "  [info] Recommended: SonarQube for IDE (SonarLint) in connected mode for in-editor feedback "
            "(see docs/providers.md)"
        )


def _git_hook_installed(root: Path, name: str) -> bool:
    try:
        hooks_dir = subprocess.run(
            ["git", "rev-parse", "--git-path", "hooks"], cwd=root, capture_output=True, text=True, check=True
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return False
    hook = Path(hooks_dir) / name if Path(hooks_dir).is_absolute() else root / hooks_dir / name
    return hook.exists() and "pre-commit" in hook.read_text(encoding="utf-8", errors="ignore")


def cmd_doctor(args: argparse.Namespace) -> int:
    root = find_repo_root(Path(args.path))
    r = _Report()
    _log(f"slsec doctor ({__version__}) for {root}")

    pcc = root / PRE_COMMIT_CONFIG
    config: dict = {}
    if not pcc.exists():
        r.fail(f"{PRE_COMMIT_CONFIG} missing. Run `slsec init`")
    else:
        try:
            config = yaml.safe_load(pcc.read_text(encoding="utf-8")) or {}
            r.ok(f"{PRE_COMMIT_CONFIG} present")
        except yaml.YAMLError as exc:
            r.fail(f"{PRE_COMMIT_CONFIG} invalid YAML: {exc}")

    if config:
        hook_ids = {h.get("id") for repo in config.get("repos", []) or [] for h in repo.get("hooks", []) or []}
        if hook_ids & {"gitleaks", "gitleaks-system", "gitleaks-docker"}:
            r.ok("secret scanning (gitleaks) hook configured")
        else:
            r.fail("no gitleaks hook: secrets are not scanned")
        slsec_repo = find_slsec_repo(config)
        if slsec_repo is None:
            if detect_profiles(root) != ["base"]:
                r.warn("IaC files found but no slsec hooks configured. Run `slsec init --update`")
        else:
            rev = str(slsec_repo.get("rev", ""))
            if _version_tuple(rev) < _version_tuple(__version__):
                r.warn(f"slsec pinned at {rev}; latest known is v{__version__}. Run `slsec init --update`")
            else:
                r.ok(f"slsec hooks pinned at {rev}")

    try:
        cfg = load_config(root)
        r.ok(f"settings: mode={cfg.mode}" + (f" ({cfg.source.name})" if cfg.source else " (defaults; no .slsec.yaml)"))
        for s in cfg.checkov_expired:
            r.warn(f"exception {s.id} expired {s.expires}: check is enforced again ({s.reason})")
    except ConfigError as exc:
        r.fail(f"settings invalid: {exc}")

    _doctor_providers(r, root, config, args)

    if not args.ci:
        if shutil.which("pre-commit"):
            r.ok("pre-commit installed")
        else:
            r.fail("pre-commit not on PATH (uv tool install pre-commit | pipx install pre-commit)")
        try:
            hooks_dir = subprocess.run(
                ["git", "rev-parse", "--git-path", "hooks"], cwd=root, capture_output=True, text=True, check=True
            ).stdout.strip()
            hook = (root / hooks_dir / "pre-commit") if not Path(hooks_dir).is_absolute() else Path(hooks_dir) / "pre-commit"
            if hook.exists() and "pre-commit" in hook.read_text(encoding="utf-8", errors="ignore"):
                r.ok("git pre-commit hook active")
            else:
                r.fail("git pre-commit hook not installed: run `pre-commit install --hook-type pre-commit --hook-type pre-push`")
        except (OSError, subprocess.CalledProcessError):
            r.warn("could not locate git hooks directory")

    _log(f"\n{r.failures} failure(s), {r.warnings} warning(s)")
    return 1 if r.failures else 0


# --------------------------------------------------------------------------- ci


def cmd_ci(args: argparse.Namespace) -> int:
    """Run the same hooks developers run, over the whole repo, writing reports."""
    root = find_repo_root(Path(args.path))
    pre_commit = shutil.which("pre-commit")
    if not pre_commit:
        _log("error: pre-commit not installed (pip install pre-commit)")
        return 2
    env = dict(os.environ)
    report_dir = Path(args.report_dir).resolve()
    report_dir.mkdir(parents=True, exist_ok=True)
    env["SLSEC_REPORT_DIR"] = str(report_dir)
    env["SLSEC_CI"] = "1"
    worst = 0
    for stage in ("pre-commit", "pre-push"):
        _log(f"::group::slsec {stage} hooks" if env.get("GITHUB_ACTIONS") else f"== slsec {stage} hooks")
        cmd = [pre_commit, "run", "--all-files", "--show-diff-on-failure", "--color=always", "--hook-stage", stage]
        rc = subprocess.run(cmd, cwd=root, env=env).returncode
        if env.get("GITHUB_ACTIONS"):
            _log("::endgroup::")
        worst = max(worst, rc)
    _log(f"Reports: {report_dir}")
    return worst


# --------------------------------------------------------------------------- entry


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(prog="slsec", description="Shift-left security: drop-in pre-commit hooks and policy.")
    p.add_argument("--version", action="version", version=f"slsec {__version__}")
    sub = p.add_subparsers(dest="command", required=True)

    i = sub.add_parser("init", help="add slsec hooks + config to a repo")
    i.add_argument("path", nargs="?", default=".")
    i.add_argument("--profile", help=f"comma-separated: {', '.join(PROFILES)} (default: auto-detect)")
    i.add_argument("--mode", choices=MODES, default="warn", help="IaC/lint findings: warn (default) or block")
    i.add_argument("--sca", choices=SCA_PROVIDERS, default=None, help="pre-push dependency scanner (default: none, or the value in .slsec.yaml with --update)")
    i.add_argument("--sast-engine", dest="sast_engine", choices=SAST_ENGINES, default=None, help="commit-stage SAST engine (default: opengrep, or the value in .slsec.yaml with --update)")
    i.add_argument("--update", action="store_true", help="refresh pins using the profiles recorded in .slsec.yaml")
    i.add_argument("--force", action="store_true", help="replace tool config files that differ (keeps .bak)")
    i.add_argument("--no-install", action="store_true", help="don't run `pre-commit install`")
    i.add_argument("--source-url", help="git URL of the slsec repo (default: $SLSEC_SOURCE_URL or built-in)")
    i.add_argument("--rev", help=f"slsec tag to pin (default: v{__version__})")
    i.set_defaults(func=cmd_init)

    d = sub.add_parser("doctor", help="check that slsec is set up correctly in a repo")
    d.add_argument("path", nargs="?", default=".")
    d.add_argument("--ci", action="store_true", help="skip local-only checks (git hook, pre-commit on PATH)")
    d.set_defaults(func=cmd_doctor)

    c = sub.add_parser("ci", help="run all hooks over the whole repo and write SARIF/JUnit reports")
    c.add_argument("path", nargs="?", default=".")
    c.add_argument("--report-dir", default="slsec-reports")
    c.set_defaults(func=cmd_ci)
    return p


def main(argv: Optional[Sequence[str]] = None) -> None:
    args = build_parser().parse_args(argv)
    sys.exit(args.func(args))


if __name__ == "__main__":
    main()
