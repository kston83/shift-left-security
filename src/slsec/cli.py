def cmd_ci(args: argparse.Namespace) -> int:
    """Run the same hooks developers run, over the whole repo, writing reports."""
    root = find_repo_root(Path(args.path))
    pre_commit = shutil.which("pre-commit")
    if not pre_commit:
        _log("error: pre-commit not installed (pip install pre-commit)")
        return 2
    worst = 0
    if not getattr(args, "skip_doctor", False):
        doctor_args = argparse.Namespace(
            path=str(root), ci=True,
            require_mode=getattr(args, "require_mode", None),
            require_profiles=getattr(args, "require_profiles", None),
        )
        worst = cmd_doctor(doctor_args)
    env = dict(os.environ)
    report_dir = Path(args.report_dir).resolve()
    report_dir.mkdir(parents=True, exist_ok=True)
    env["SLSEC_REPORT_DIR"] = str(report_dir)
    env["SLSEC_CI"] = "1"
    # one id for every hook invocation, so pre-commit's file batches add up in one report
    env.setdefault(reports.RUN_ID_ENV, reports.new_run_id())
    for stage in ("pre-commit", "pre-push"):
        _log(f"::group::slsec {stage} hooks" if env.get("GITHUB_ACTIONS") else f"== slsec {stage} hooks")
        cmd = [pre_commit, "run", "--all-files", "--show-diff-on-failure", "--color=always", "--hook-stage", stage]
        rc = subprocess.run(cmd, cwd=root, env=env).returncode
        if env.get("GITHUB_ACTIONS"):
            _log("::endgroup::")
        worst = max(worst, rc)
    _log(f"Reports: {report_dir}")
    return worst


