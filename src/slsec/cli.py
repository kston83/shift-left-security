def parse_version(rev: object) -> Optional[tuple]:
    """(1, 2, 3, 1) for v1.2.3, (1, 2, 3, 0) for a pre-release like v1.2.3-rc1, None for a SHA or branch."""
    m = re.match(r"^v?(\d+(?:\.\d+)*)(.*)$", str(rev or "").strip())
    if not m:
        return None
    nums = tuple(int(x) for x in m.group(1).split("."))
    nums = nums + (0,) * (4 - len(nums)) if len(nums) < 4 else nums
    return nums + (0 if m.group(2) else 1,)


def is_newer(candidate: object, current: object) -> bool:
    """Is `candidate` a strictly newer version than `current`? Unknown forms never count as newer."""
    new, cur = parse_version(candidate), parse_version(current)
    return new is not None and cur is not None and new > cur


def _eol_comment(mapping: dict, key: str) -> str:
    if not isinstance(mapping, CommentedMap):
        return ""
    entry = mapping.ca.items.get(key)
    token = entry[2] if entry and len(entry) > 2 else None
    return str(getattr(token, "value", "") or "")


def frozen_tag(repo: dict) -> Optional[str]:
    """The tag behind a frozen SHA rev (`rev: <sha>  # frozen: v1.2.3`), as written by `pre-commit autoupdate --freeze`."""
    m = FROZEN_RE.search(_eol_comment(repo, "rev").split("\n", 1)[0])
    return m.group(1) if m else None


def _drop_frozen_comment(repo: dict) -> None:
    """Remove a `# frozen:` end-of-line comment from `rev`, keeping any comment lines that follow it."""
    if not isinstance(repo, CommentedMap):
        return
    entry = repo.ca.items.get("rev")
    token = entry[2] if entry and len(entry) > 2 else None
    if token is None or not FROZEN_RE.search(str(token.value).split("\n", 1)[0]):
        return
    rest = str(token.value).split("\n", 1)[1] if "\n" in str(token.value) else ""
    if rest.strip():
        token.value = "\n" + rest
    else:
        entry[2] = None


def set_rev(repo: dict, rev: str, frozen: Optional[str] = None) -> None:
    repo["rev"] = rev
    _drop_frozen_comment(repo)
    if frozen and isinstance(repo, CommentedMap):
        repo.yaml_add_eol_comment(f"frozen: {frozen}", "rev")


def current_version(repo: dict) -> object:
    """The version a repo is pinned at: the tag for a frozen SHA, otherwise `rev` itself."""
    return frozen_tag(repo) or repo.get("rev")


def _split_dep(dep: str) -> tuple:
    """('github.com/x/tflint', 'v0.66.0') from 'github.com/x/tflint@v0.66.0' (also name==1.2)."""
    for sep in ("==", "@"):
        name, found, ver = str(dep).rpartition(sep)
        if found and name and ver:
            return name, ver, sep
    return str(dep), None, None


def bump_dependencies(current: Sequence[str], wanted: Sequence[str]) -> List[str]:
    """Raise pinned versions in `current` to `wanted` where that's an upgrade; never lower one."""
    result = [str(d) for d in current]
    names = {_split_dep(d)[0]: i for i, d in enumerate(result)}
    for dep in wanted:
        name, ver, sep = _split_dep(dep)
        if name not in names:
            result.append(str(dep))
            continue
        i = names[name]
        _, cur_ver, _ = _split_dep(result[i])
        if ver is not None and (cur_ver is None or is_newer(ver, cur_ver)):
            result[i] = str(dep)
    return result


def _merge_repo(into: dict, new: dict, force_rev: bool = False) -> None:
    """Merge a profile fragment's repo into the existing one.

    The rev only moves forward: a pin that Renovate (or a person) already raised
    past slsec's is kept. `force_rev` (an explicit `--rev`) sets it regardless.
    """
    if "rev" in new:
        if "rev" not in into or force_rev or is_newer(new["rev"], current_version(into)):
            set_rev(into, new["rev"])
    hooks = into.get("hooks")
    if hooks is None:
        hooks = into["hooks"] = CommentedSeq()
    existing_ids = {h.get("id") for h in hooks}
    for hook in new.get("hooks", []):
        if hook.get("id") not in existing_ids:
            hooks.append(hook)
        elif into.get("repo") == "local" and "additional_dependencies" in hook:
            # local hooks carry their tool pin in additional_dependencies; refresh only
            # that, so a team's own args/files/entry tweaks survive `init --update`
            for h in hooks:
                if h.get("id") == hook.get("id"):
                    deps = bump_dependencies(h.get("additional_dependencies") or [], hook["additional_dependencies"])
                    if deps != list(h.get("additional_dependencies") or []):
                        h["additional_dependencies"] = deps


def load_sca_fragment(provider: str) -> dict:
    return yaml.safe_load(bundled_text("templates", "sca", f"{provider}.yaml")) or {}


def _remove_hooks(repos: List[dict], hook_ids: set) -> None:
    # Edit in place (only when something goes) so ruamel keeps the comments on what stays.
    for repo in repos:
        hooks = repo.get("hooks")
        if hooks:
            for i in reversed(range(len(hooks))):
                if hooks[i].get("id") in hook_ids:
                    del hooks[i]
    for i in reversed(range(len(repos))):
        if "hooks" in repos[i] and not repos[i].get("hooks"):
            del repos[i]


def _apply_sast_engine(repos: List[dict], sast_engine: str) -> None:
    """semgrep needs the engine installed in the hook env; any other engine drops that pin."""
    for repo in repos:
        for hook in repo.get("hooks", []) or []:
            if hook.get("id") != "slsec-sast":
                continue
            current = list(hook.get("additional_dependencies", []) or [])
            deps = [d for d in current if not str(d).startswith("semgrep")]
            if sast_engine == "semgrep":
                keep = [d for d in current if str(d).startswith("semgrep")]
                deps += keep or [SEMGREP_DEPENDENCY]
            if deps == current:
                continue
            if deps:
                hook["additional_dependencies"] = deps
            else:
                hook.pop("additional_dependencies", None)


def _insert_key(config: CommentedMap, key: str, value: object, after: Sequence[str] = ()) -> None:
    """Add a top-level key just after the keys in `after` (or first), without disturbing the rest."""
    if key in config:
        return
    pos = 0
    for i, k in enumerate(config):
        if k in after:
            pos = i + 1
    config.insert(pos, key, value)


def compose_config(
    profiles: Sequence[str],
    source_url: str,
    rev: str,
    existing: Optional[CommentedMap] = None,
    sca: str = "none",
    sast_engine: str = "opengrep",
    force_rev: bool = False,
) -> CommentedMap:
    """Merge profile fragments into one pre-commit config.

    `existing` (a ruamel round-trip mapping) is edited in place, so its comments,
    key order and quoting survive. Pins only move forward unless `force_rev`.
    """
    config = existing if isinstance(existing, CommentedMap) else CommentedMap(existing or {})
    _insert_key(config, "default_stages", ["pre-commit"])
    if "repos" not in config or config["repos"] is None:
        config["repos"] = CommentedSeq()
    repos = config["repos"]
    index = {_repo_key(r): r for r in repos}
    fragments = [load_profile(n) for n in ["base", *[p for p in profiles if p != "base"]]]
    if sca != "none":
        fragments.append(load_sca_fragment(sca))
    for fragment in fragments:
        for repo in fragment.get("repos", []):
            hooks = [CommentedMap(h) for h in repo.get("hooks", [])]
            if repo.get("repo") == SLSEC_PLACEHOLDER:
                repo = CommentedMap([("repo", source_url), ("rev", rev), ("hooks", hooks)])
                force = force_rev
            else:
                repo = CommentedMap(repo)
                repo["hooks"] = hooks
                force = False
            key = _repo_key(repo)
            if key in index:
                _merge_repo(index[key], repo, force_rev=force)
            else:
                index[key] = repo
                repos.append(repo)
    # switching provider: drop the other providers' hooks (the only hooks slsec ever removes)
    _remove_hooks(repos, {f"slsec-{p}" for p in SCA_PROVIDERS if p not in ("none", sca)})
    _apply_sast_engine(repos, sast_engine)
    if sca != "none":
        types = config.get("default_install_hook_types")
        if types is None:
            _insert_key(config, "default_install_hook_types", ["pre-commit", "pre-push"], after=("default_stages",))
        else:
            for hook_type in ("pre-commit", "pre-push"):
                if hook_type not in types:
                    types.append(hook_type)
    return config


def _yaml(indent: int = 2, block_seq_indent: int = 0) -> YAML:
    """Round-trip YAML (keeps comments, key order, quoting) in the file's own layout.

    `indent` / `block_seq_indent` are what ruamel's load_yaml_guess_indent reports:
    2/0 for `- repo:` flush with its key (PyYAML, our default), 4/2 for `  - repo:`.
    """
    y = YAML()
    y.preserve_quotes = True
    y.width = 4096  # never fold long regexes / entries
    offset = block_seq_indent if 0 <= block_seq_indent < indent else 0
    y.indent(mapping=max(2, offset), sequence=max(indent, offset + 2), offset=offset)
    return y


def load_config_text(text: str) -> tuple:
    """(round-trip config, YAML dumper matching the file's indentation)."""
    data, indent, block_seq_indent = load_yaml_guess_indent(text)
    y = _yaml(indent or 2, block_seq_indent or 0)
    data = y.load(text)  # reload with our settings (preserve_quotes)
    if data is None:
        data = CommentedMap()
    if not isinstance(data, CommentedMap):
        raise RuamelYAMLError("top level must be a mapping")
    return data, y


def dump_config(config: CommentedMap, source_url: str, dumper: Optional[YAML] = None) -> str:
    stream = io.StringIO()
    (dumper or _yaml()).dump(config, stream)
    body = stream.getvalue()
    if HEADER_VERSION.search(body):
        return HEADER_VERSION.sub(lambda m: m.group(1) + __version__, body, count=1)
    return HEADER.format(version=__version__, source=source_url) + body


def resolve_tag(url: str, tag: str, timeout: int = 60) -> Optional[str]:
    """The commit SHA a tag points to (peeled for annotated tags), via `git ls-remote`."""
    try:
        out = subprocess.run(
            ["git", "ls-remote", "--tags", url, f"refs/tags/{tag}", f"refs/tags/{tag}^{{}}"],
            capture_output=True, text=True, timeout=timeout,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    if out.returncode != 0:
        return None
    refs = {}
    for line in out.stdout.splitlines():
        sha, _, ref = line.partition("\t")
        refs[ref.strip()] = sha.strip()
    sha = refs.get(f"refs/tags/{tag}^{{}}") or refs.get(f"refs/tags/{tag}")
    return sha if sha and SHA_RE.match(sha) else None


def freeze_revs(config: dict, resolve=resolve_tag) -> List[str]:
    """Pin every remote repo's tag to its commit SHA, keeping the tag in a `# frozen:` comment.

    Same format as `pre-commit autoupdate --freeze`. Returns the repos that couldn't be resolved.
    """
    failed = []
    for repo in config.get("repos") or []:
        url, rev = str(repo.get("repo", "")), str(repo.get("rev", ""))
        if url in ("local", "meta") or not rev or SHA_RE.match(rev):
            continue
        sha = resolve(url, rev)
        if sha:
            set_rev(repo, sha, frozen=rev)
        else:
            failed.append(f"{url}@{rev}")
    return failed


def _write(path: Path, text: str) -> None:
    # explicit LF so generated files don't flip line endings on Windows
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)


def _set_provider(text: str, key: str, value: str) -> str:
    """Rewrite `providers.<key>` in place, keeping the file's comments."""
    return re.sub(rf"^(\s+{key}:\s*)[A-Za-z]+", rf"\g<1>{value}", text, count=1, flags=re.M)


def _backup(path: Path) -> Path:
    bak = path.with_name(path.name + ".bak")
    shutil.copy2(path, bak)
    return bak


def _write_if_changed(path: Path, content: str, overwrite: bool) -> str:
    if path.exists():
        current = path.read_text(encoding="utf-8")
        if current == content:
            return "unchanged"
        if not overwrite:
            return "kept (differs from slsec default; use --force to replace)"
        bak = _backup(path)
        _write(path, content)
        return f"replaced (previous saved as {bak.name})"
    _write(path, content)
    return "created"


def _run(cmd: Sequence[str], cwd: Path) -> int:
    try:
        return subprocess.run(list(cmd), cwd=cwd).returncode
    except OSError as exc:
        _log(f"  ! could not run {cmd[0]}: {exc}")
        return 127


